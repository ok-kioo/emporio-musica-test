"""Persistence port for the active policy-version pointer."""

from typing import Protocol

from src.domain.models.policy_version import PolicyVersion


class PolicyVersionRegistryRepository(Protocol):
    def active(self) -> PolicyVersion | None: ...
    def activate(self, version: str) -> PolicyVersion: ...
    def rollback(self) -> PolicyVersion | None: ...
    def list(self) -> list[PolicyVersion]: ...
